-- Generates simple-disenchant-tooltip/Data/ObservedItems.lua and Data/ObservedLevels.lua.
--
-- data/<material>.csv (e.g. greater-magic-essence.csv): one item name per line, the items
-- seen to disenchant into that material.
--
-- data/level-ranges.csv (optional): item-level ranges each material was observed at, with
-- outliers already removed. Header and rows:
--   material,quality,type,min,max
--   strange-dust,UNCOMMON,ARMOR,5,26
-- material = file slug, quality = UNCOMMON|RARE|EPIC, type = ARMOR|WEAPON|ANY.
--
-- Run from the repo root: lua scripts/generate_observed_items.lua

local root = arg[0]:match("^(.*)[/\\]scripts[/\\]") or "."
local addonRoot = root .. "/simple-disenchant-tooltip"

dofile(addonRoot .. "/Data/Tables.lua")
local Tables = SimpleDisenchantTooltip.Tables

local function slug(name)
  return (name:lower():gsub("%s+", "-"))
end

local idBySlug = {}
for id, name in pairs(Tables.MATERIAL_NAMES) do
  idBySlug[slug(name)] = id
end

local files = {}
local list = io.popen('dir /b "' .. root:gsub("/", "\\") .. '\\data\\*.csv" 2>nul')
if list then
  for line in list:lines() do
    files[#files + 1] = line
  end
  list:close()
end
if #files == 0 then
  list = io.popen('ls "' .. root .. '/data"/*.csv 2>/dev/null')
  for line in list:lines() do
    files[#files + 1] = line:match("([^/\\]+)$")
  end
  list:close()
end
table.sort(files)

local byItem = {}
local itemCount = 0
local RANGES_FILE = "level-ranges.csv"

for _, file in ipairs(files) do
  if file ~= RANGES_FILE then
  local materialSlug = file:gsub("%.csv$", "")
  local materialId = idBySlug[materialSlug]
  if not materialId then
    error("No material id for data/" .. file .. " (add it to Tables.MATERIAL_NAMES)")
  end
  for line in io.lines(root .. "/data/" .. file) do
    local name = line:gsub("^\239\187\191", ""):gsub("^%s+", ""):gsub("%s+$", "")
    if name:match("^%d+$") then
      error("data/" .. file .. " holds numbers, not item names: " .. name)
    end
    if name ~= "" then
      local ids = byItem[name]
      if not ids then
        ids = {}
        byItem[name] = ids
        itemCount = itemCount + 1
      end
      local seen = false
      for i = 1, #ids do
        if ids[i] == materialId then
          seen = true
        end
      end
      if not seen then
        ids[#ids + 1] = materialId
      end
    end
  end
  end
end

local names = {}
for name in pairs(byItem) do
  names[#names + 1] = name
end
table.sort(names)

local out = {
  "-- GENERATED by scripts/generate_observed_items.lua from data/*.csv. Do not edit by hand.",
  "-- Item name -> material ids it has been seen to disenchant into.",
  "SimpleDisenchantTooltip = SimpleDisenchantTooltip or {}",
  "SimpleDisenchantTooltip.ObservedItems = {",
}
for _, name in ipairs(names) do
  local ids = byItem[name]
  table.sort(ids)
  local strs = {}
  for i = 1, #ids do
    strs[i] = tostring(ids[i])
  end
  out[#out + 1] = string.format("  [%q] = { %s },", name, table.concat(strs, ", "))
end
out[#out + 1] = "}"
out[#out + 1] = ""

local f = assert(io.open(addonRoot .. "/Data/ObservedItems.lua", "wb"))
f:write(table.concat(out, "\n"))
f:close()
print(string.format("Wrote %d items from %d files", itemCount, #files))

-- Level ranges ---------------------------------------------------------------------
local QUALITIES = { UNCOMMON = true, RARE = true, EPIC = true }
local TYPES = { ARMOR = true, WEAPON = true, ANY = true }
local ranges = {}
local rangeCount = 0
local rf = io.open(root .. "/data/" .. RANGES_FILE, "rb")
if rf then
  local lineNo = 0
  for line in rf:lines() do
    lineNo = lineNo + 1
    line = line:gsub("^\239\187\191", ""):gsub("\r$", "")
    if lineNo > 1 and line:match("%S") then
      local slugName, quality, itemType, lo, hi =
        line:match("^%s*([^,]+),%s*([^,]+),%s*([^,]+),%s*(%d+),%s*(%d+)%s*$")
      local where = string.format("%s line %d", RANGES_FILE, lineNo)
      assert(slugName, where .. ": expected material,quality,type,min,max")
      local id = assert(idBySlug[slugName], where .. ": unknown material " .. slugName)
      assert(QUALITIES[quality], where .. ": bad quality " .. quality)
      assert(TYPES[itemType], where .. ": bad type " .. itemType)
      lo, hi = tonumber(lo), tonumber(hi)
      assert(lo <= hi, where .. ": min > max")
      ranges[id] = ranges[id] or {}
      ranges[id][quality] = ranges[id][quality] or {}
      assert(not ranges[id][quality][itemType], where .. ": duplicate row")
      ranges[id][quality][itemType] = { lo, hi }
      rangeCount = rangeCount + 1
    end
  end
  rf:close()
end

local ids = {}
for id in pairs(ranges) do
  ids[#ids + 1] = id
end
table.sort(ids)
local lv = {
  "-- GENERATED by scripts/generate_observed_items.lua from data/level-ranges.csv. Do not edit by hand.",
  "-- materialId -> quality -> type -> { minLevel, maxLevel } (item levels the material was observed at).",
  "SimpleDisenchantTooltip = SimpleDisenchantTooltip or {}",
  "SimpleDisenchantTooltip.ObservedLevels = {",
}
for _, id in ipairs(ids) do
  lv[#lv + 1] = string.format("  [%d] = {", id)
  for _, quality in ipairs({ "UNCOMMON", "RARE", "EPIC" }) do
    local byType = ranges[id][quality]
    if byType then
      local parts = {}
      for _, itemType in ipairs({ "ARMOR", "WEAPON", "ANY" }) do
        local r = byType[itemType]
        if r then
          parts[#parts + 1] = string.format("%s = { %d, %d }", itemType, r[1], r[2])
        end
      end
      lv[#lv + 1] = string.format("    %s = { %s },", quality, table.concat(parts, ", "))
    end
  end
  lv[#lv + 1] = "  },"
end
lv[#lv + 1] = "}"
lv[#lv + 1] = ""
local lf = assert(io.open(addonRoot .. "/Data/ObservedLevels.lua", "wb"))
lf:write(table.concat(lv, "\n"))
lf:close()
print(string.format("Wrote %d level ranges for %d materials", rangeCount, #ids))
