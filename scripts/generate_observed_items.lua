-- Generates simple-disenchant-tooltip/Data/ObservedItems.lua from data/*.csv.
-- Each CSV is named after a material (e.g. greater-magic-essence.csv) and lists,
-- one per line, the item names seen to disenchant into that material.
-- Run from the repo root: lua scripts/generate_observed_items.lua

local root = arg[0]:match("^(.*)[/\\]scripts[/\\]") or "."
local addonRoot = root .. "/simple-disenchant-tooltip"

dofile(addonRoot .. "/Data/Tables.lua")
local Tables = SimpleDisenchantTooltip.Tables

local function slug(name)
  return (name:lower():gsub("%s+", "-"))
end

local idBySlug = {}
for id, name in pairs(Tables.MATERIAL_NAMES) do
  idBySlug[slug(name)] = id
end

local files = {}
local list = io.popen('dir /b "' .. root:gsub("/", "\\") .. '\\data\\*.csv" 2>nul')
if list then
  for line in list:lines() do
    files[#files + 1] = line
  end
  list:close()
end
if #files == 0 then
  list = io.popen('ls "' .. root .. '/data"/*.csv 2>/dev/null')
  for line in list:lines() do
    files[#files + 1] = line:match("([^/\\]+)$")
  end
  list:close()
end
table.sort(files)

local byItem = {}
local itemCount = 0
for _, file in ipairs(files) do
  local materialSlug = file:gsub("%.csv$", "")
  local materialId = idBySlug[materialSlug]
  if not materialId then
    error("No material id for data/" .. file .. " (add it to Tables.MATERIAL_NAMES)")
  end
  for line in io.lines(root .. "/data/" .. file) do
    local name = line:gsub("^\239\187\191", ""):gsub("^%s+", ""):gsub("%s+$", "")
    if name ~= "" then
      local ids = byItem[name]
      if not ids then
        ids = {}
        byItem[name] = ids
        itemCount = itemCount + 1
      end
      local seen = false
      for i = 1, #ids do
        if ids[i] == materialId then
          seen = true
        end
      end
      if not seen then
        ids[#ids + 1] = materialId
      end
    end
  end
end

local names = {}
for name in pairs(byItem) do
  names[#names + 1] = name
end
table.sort(names)

local out = {
  "-- GENERATED by scripts/generate_observed_items.lua from data/*.csv. Do not edit by hand.",
  "-- Item name -> material ids it has been seen to disenchant into.",
  "SimpleDisenchantTooltip = SimpleDisenchantTooltip or {}",
  "SimpleDisenchantTooltip.ObservedItems = {",
}
for _, name in ipairs(names) do
  local ids = byItem[name]
  table.sort(ids)
  local strs = {}
  for i = 1, #ids do
    strs[i] = tostring(ids[i])
  end
  out[#out + 1] = string.format("  [%q] = { %s },", name, table.concat(strs, ", "))
end
out[#out + 1] = "}"
out[#out + 1] = ""

local f = assert(io.open(addonRoot .. "/Data/ObservedItems.lua", "wb"))
f:write(table.concat(out, "\n"))
f:close()
print(string.format("Wrote %d items from %d files", itemCount, #files))
