-- Pure helpers: build Data/ObservedLevels.lua from a saved BootyBayBroker disenchant page.
-- No I/O here; see scripts/update_observed_levels.lua for the CLI.
local M = {}

M.SOURCE_URL = "https://bootybaybroker.com/forever/crafting/disenchant"

local QUALITY_ORDER = { "UNCOMMON", "RARE", "EPIC" }
local TYPE_ORDER = { "ARMOR", "WEAPON", "ANY" }

-- Returns the first <table> whose <caption> starts with captionPrefix.
local function find_table(html, caption_prefix)
  local cap_start = html:find("<caption>" .. caption_prefix, 1, true)
  if not cap_start then
    return nil
  end
  local tbl_start
  local pos = 1
  while true do
    local s = html:find("<table", pos, true)
    if not s or s > cap_start then
      break
    end
    tbl_start = s
    pos = s + 1
  end
  local _, tbl_end = html:find("</table>", cap_start, true)
  if not tbl_start or not tbl_end then
    return nil
  end
  return html:sub(tbl_start, tbl_end)
end

local function each_row(tbl)
  return tbl:gmatch('<tr role="row"[^>]*>(.-)</tr>')
end

--- name -> item id, from the "Disenchant materials" table.
function M.parse_materials(html)
  local tbl = find_table(html, "Disenchant materials")
  if not tbl then
    return nil, "materials table not found (page layout changed?)"
  end
  local map, count = {}, 0
  for id, name in tbl:gmatch('item/(%d+)/[^"]*"><span data%-slot="item%-name"[^>]*>([^<]+)</span>') do
    map[name] = tonumber(id)
    count = count + 1
  end
  if count == 0 then
    return nil, "no materials found in materials table"
  end
  return map
end

--- rows: { quality = "UNCOMMON", type = "ARMOR", min = 5, max = 15, results = { "Strange Dust", ... } }
function M.parse_rows(html)
  local tbl = find_table(html, "What each quality")
  if not tbl then
    return nil, "odds table not found (page layout changed?)"
  end
  local rows = {}
  for row in each_row(tbl) do
    local label = row:match('class="quality%-%w+">([^<]+)</span>')
    local lo, hi = row:match('data%-numeric="true">%s*(%d+) to (%d+)%s*<')
    if label and lo and hi then
      local quality, class = label:match("^(%a+)%s+(%a+)$")
      if not quality then
        return nil, "unrecognised row label: " .. label
      end
      local results = {}
      for text in row:gmatch('<li [^>]*><span data%-slot="chance">[^<]*</span><span>([^<]*)</span>') do
        results[#results + 1] = text:match("^(.-),") or text
      end
      if #results == 0 then
        return nil, "row without results: " .. label .. " " .. lo .. "-" .. hi
      end
      rows[#rows + 1] = {
        quality = quality:upper(),
        type = class:upper(),
        min = tonumber(lo),
        max = tonumber(hi),
        results = results,
      }
    end
  end
  if #rows == 0 then
    return nil, "no odds rows found"
  end
  return rows
end

--- levels[materialId][QUALITY][TYPE] = { min, max }. Uncommon keeps ARMOR/WEAPON; Rare/Epic merge to ANY.
function M.build(rows, materials)
  local levels = {}
  for _, row in ipairs(rows) do
    local type_key = row.quality == "UNCOMMON" and row.type or "ANY"
    if row.quality ~= "UNCOMMON" and row.quality ~= "RARE" and row.quality ~= "EPIC" then
      return nil, "unknown quality: " .. row.quality
    end
    if type_key ~= "ARMOR" and type_key ~= "WEAPON" and type_key ~= "ANY" then
      return nil, "unknown item class: " .. row.type
    end
    for _, name in ipairs(row.results) do
      local id = materials[name]
      if not id then
        return nil, "result material not in materials table: " .. name
      end
      levels[id] = levels[id] or {}
      levels[id][row.quality] = levels[id][row.quality] or {}
      local band = levels[id][row.quality][type_key]
      if band then
        band[1] = math.min(band[1], row.min)
        band[2] = math.max(band[2], row.max)
      else
        levels[id][row.quality][type_key] = { row.min, row.max }
      end
    end
  end
  return levels
end

function M.from_html(html)
  local materials, err = M.parse_materials(html)
  if not materials then
    return nil, err
  end
  local rows
  rows, err = M.parse_rows(html)
  if not rows then
    return nil, err
  end
  return M.build(rows, materials)
end

function M.render(levels)
  local ids = {}
  for id in pairs(levels) do
    ids[#ids + 1] = id
  end
  table.sort(ids)
  local out = {
    "-- Generated by scripts/update_observed_levels.lua from BootyBayBroker; do not edit by hand.",
    "-- Source: " .. M.SOURCE_URL,
    "-- materialId -> quality -> type -> { minLevel, maxLevel } (union of the item-level bands the material drops at).",
    "SimpleDisenchantTooltip = SimpleDisenchantTooltip or {}",
    "SimpleDisenchantTooltip.ObservedLevels = {",
  }
  for _, id in ipairs(ids) do
    out[#out + 1] = string.format("  [%d] = {", id)
    for _, quality in ipairs(QUALITY_ORDER) do
      local by_type = levels[id][quality]
      if by_type then
        local parts = {}
        for _, t in ipairs(TYPE_ORDER) do
          local band = by_type[t]
          if band then
            parts[#parts + 1] = string.format("%s = { %d, %d }", t, band[1], band[2])
          end
        end
        out[#out + 1] = string.format("    %s = { %s },", quality, table.concat(parts, ", "))
      end
    end
    out[#out + 1] = "  },"
  end
  out[#out + 1] = "}"
  return table.concat(out, "\n") .. "\n"
end

--- Load an existing ObservedLevels.lua text into a levels table (nil on failure).
function M.load(text)
  local env = { SimpleDisenchantTooltip = nil }
  local chunk
  if setfenv then
    chunk = loadstring(text, "=ObservedLevels")
    if chunk then
      setfenv(chunk, env)
    end
  else
    chunk = load(text, "=ObservedLevels", "t", env)
  end
  if not chunk then
    return nil
  end
  local ok = pcall(chunk)
  local root = env.SimpleDisenchantTooltip
  if not ok or type(root) ~= "table" then
    return nil
  end
  return root.ObservedLevels
end

--- Human-readable list of changed bands between two levels tables.
function M.diff(old, new)
  old = old or {}
  local lines = {}
  local function band_str(b)
    return b and (b[1] .. "-" .. b[2]) or "none"
  end
  local seen = {}
  local function walk(id)
    if seen[id] then
      return
    end
    seen[id] = true
    for _, q in ipairs(QUALITY_ORDER) do
      for _, t in ipairs(TYPE_ORDER) do
        local a = old[id] and old[id][q] and old[id][q][t]
        local b = new[id] and new[id][q] and new[id][q][t]
        if band_str(a) ~= band_str(b) then
          lines[#lines + 1] = string.format("  %d %s %s: %s -> %s", id, q, t, band_str(a), band_str(b))
        end
      end
    end
  end
  local ids = {}
  for id in pairs(new) do ids[#ids + 1] = id end
  for id in pairs(old) do if not new[id] then ids[#ids + 1] = id end end
  table.sort(ids)
  for _, id in ipairs(ids) do
    walk(id)
  end
  return lines
end

return M
